import { useEffect, useState } from "react";
import { films, books } from "../data/films.js";
import { setAmbientScene, sfxConfirm } from "../audio/sound.js";
import PageMeta from "../components/PageMeta.jsx";

/* Build a downloadable "case file" — our own write-up of the entry, so
   nothing copyrighted is ever hosted or redistributed here. */
function caseFileText(item, isFilm) {
  const head = [
    "FAZBEAR ARCHIVE · CASE FILE",
    "===========================",
    `${item.title} (${item.year})`,
    item.director ? `Directed by ${item.director}` : null,
    item.author ? `Written by ${item.author}` : null,
    item.series || item.studio ? `Series / studio: ${item.series || item.studio}` : null,
    item.boxOffice ? `Box office: ${item.boxOffice}` : null,
    item.runtime ? `Runtime: ${item.runtime}` : null,
    "",
    "SUMMARY",
    item.summary,
    "",
    "FULL ENTRY",
    item.detail,
  ].filter(Boolean);

  const highlights = item.highlights || item.trivia || [];
  if (highlights.length) {
    head.push("", isFilm ? "PRODUCTION NOTES" : "WHY READ IT");
    highlights.forEach((line) => head.push(`· ${line}`));
  }
  head.push(
    "",
    "---",
    "Generated by the FNAF Wiki fan project. This file is original wiki text;",
    "the underlying work is (c) its respective rights holders. Support the"
  );
  head.push(
    isFilm ? "official release." : "official release by buying the book."
  );
  return head.join("\n");
}

function downloadCaseFile(item, isFilm) {
  try {
    const blob = new Blob([caseFileText(item, isFilm)], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${item.id || "fazbear"}-case-file.txt`;
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1500);
  } catch {
    /* downloads can be blocked — the button simply does nothing then */
  }
}

function MediaCard({ item, isFilm }) {
  const facts = [
    isFilm && item.release && ["Released", item.release],
    isFilm && item.runtime && ["Runtime", item.runtime],
    item.author && ["Author", item.author],
    item.director && ["Director", item.director],
    item.boxOffice && ["Box office", item.boxOffice],
  ].filter(Boolean);

  const highlights = item.highlights || item.trivia;

  return (
    <article
      className="card media-card"
      style={{ "--media-accent": item.accent }}
    >
      <div className="media-head">
        <img
          className="media-poster"
          src={item.image}
          alt={`${item.title} cover art`}
          loading="eager"
          decoding="async"
        />
        <div className="media-head-body">
          <div className="media-meta">
            {item.year} · {item.series || item.studio}
          </div>
          <div className="card-title">{item.title}</div>
          {item.director && (
            <div className="media-meta">Directed by {item.director}</div>
          )}
          {item.author && <div className="media-meta">Written by {item.author}</div>}
          {item.tagline && <div className="media-tagline">“{item.tagline}”</div>}
          <div className="card-text" style={{ marginTop: "0.6rem" }}>{item.summary}</div>
        </div>
      </div>

      <div className="media-detail">{item.detail}</div>

      {facts.length > 0 && (
        <dl className="media-facts">
          {facts.map(([label, value]) => (
            <div className="media-fact" key={label}>
              <dt>{label}</dt>
              <dd>{value}</dd>
            </div>
          ))}
        </dl>
      )}

      {item.cast && item.cast.length > 0 && (
        <div className="media-block">
          <h4>Cast &amp; crew</h4>
          <ul className="list-clean media-list">
            {item.cast.map((line) => (
              <li key={line}>{line}</li>
            ))}
          </ul>
        </div>
      )}

      {item.reception && (
        <div className="media-block">
          <h4>Reception</h4>
          <p>{item.reception}</p>
        </div>
      )}

      {highlights && highlights.length > 0 && (
        <div className="media-block">
          <h4>{isFilm ? "Production notes" : "Why read it"}</h4>
          <ul className="list-clean media-list">
            {highlights.map((line) => (
              <li key={line}>{line}</li>
            ))}
          </ul>
        </div>
      )}

      {item.notes && (
        <ul className="list-clean media-notes">
          {item.notes.map((n) => (
            <li key={n}>{n}</li>
          ))}
        </ul>
      )}

      <div className="media-actions" aria-label={`Get ${item.title}`}>
        <a
          className="media-action"
          href={`https://www.google.com/search?q=${encodeURIComponent(`buy ${item.title} ${item.author || item.director || ""}`)}`}
          target="_blank"
          rel="noopener noreferrer"
          onClick={() => sfxConfirm()}
        >
          🛒 Buy {isFilm ? "the film" : "the book"}
        </a>
        {isFilm ? (
          <a
            className="media-action"
            href={`https://www.youtube.com/results?search_query=${encodeURIComponent(`${item.title} official trailer`)}`}
            target="_blank"
            rel="noopener noreferrer"
            onClick={() => sfxConfirm()}
          >
            ▶ Watch trailer
          </a>
        ) : (
          <a
            className="media-action"
            href={`https://www.google.com/search?q=${encodeURIComponent(`read ${item.title} ${item.author || ""}`)}`}
            target="_blank"
            rel="noopener noreferrer"
            onClick={() => sfxConfirm()}
          >
            📖 Read it
          </a>
        )}
        <button
          type="button"
          className="media-action"
          onClick={() => {
            downloadCaseFile(item, isFilm);
            sfxConfirm();
          }}
        >
          ⬇ Download case file
        </button>
        <span className="media-action-note">
          {isFilm
            ? "Buy & trailer open a web search. The case file is original wiki text."
            : "Buy & read open a web search. The case file is original wiki text."}
        </span>
      </div>
    </article>
  );
}

export default function Media() {
  const [tab, setTab] = useState("films");

  /* The reading room gets a projector-whirr room tone. */
  useEffect(() => {
    setAmbientScene("media");
    return () => setAmbientScene("site");
  }, []);

  const list = tab === "films" ? films : books;

  return (
    <div className="page">
      <PageMeta
        title="Films & Books"
        description="Every Five Nights at Freddy's film and novel in depth — Blumhouse's movies with cast, box office and reception, plus the Silver Eyes trilogy, Fazbear Frights and Tales from the Pizzaplex."
      />
      <h1 className="page-title">Films &amp; Books</h1>
      <p className="page-subtitle">
        The franchise escaped the games a long time ago. Two feature films, a novel
        trilogy, and twenty volumes of short horror — each one unpacked below.
      </p>

      <div className="filter-row">
        <button className={`pill ${tab === "films" ? "active" : ""}`} onClick={() => setTab("films")}>
          🎬 Films ({films.length})
        </button>
        <button className={`pill ${tab === "books" ? "active" : ""}`} onClick={() => setTab("books")}>
          📚 Books ({books.length})
        </button>
      </div>

      <div className="grid grid-2">
        {list.map((item) => (
          <MediaCard key={item.id} item={item} isFilm={tab === "films"} />
        ))}
      </div>

      <div className="card media-continuity-note">
        <span className="hub-kicker">Continuity warning</span>
        <p>
          The films and the novels are their own timelines. They borrow names, scenes
          and ideas from the games — but events do not map one-to-one. Read them as
          parallel layers, not as proof about the game timeline.
        </p>
      </div>
    </div>
  );
}
